#!/usr/bin/env node
/*
 * Builds assets/js/search-index.js — the data behind the global search on index.html.
 *
 *   node tools/build-search-index.js
 *
 * Run it after adding or editing questions (the GitHub Pages workflow also runs it on every deploy).
 * It scans every topic page for <details class="qa"> blocks and records the question, level, tags,
 * section and a short text excerpt. Question ids follow the same q1..qN order that assets/js/app.js
 * assigns, so results can deep-link to page.html#qN.
 */
"use strict";
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const OUT = path.join(ROOT, "assets", "js", "search-index.js");
const SKIP = new Set(["index.html", "404.html"]);
const EXCERPT_CHARS = 420;

const decode = (s) => s
  .replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&quot;/g, '"').replace(/&#39;/g, "'")
  .replace(/&nbsp;/g, " ").replace(/&amp;/g, "&");
// Inline tags (code, b, a…) vanish without a gap; block tags become spaces
const text = (html) => decode(html
  .replace(/<\/?(code|b|i|em|strong|a|span|mark|kbd)\b[^>]*>/g, "")
  .replace(/<[^>]+>/g, " ")).replace(/\s+/g, " ").trim();
const attr = (tag, name) => { const m = tag.match(new RegExp(name + '="([^"]*)"')); return m ? decode(m[1]) : ""; };

const hasTag = (tag, name) => (" " + attr(tag, "data-tag") + " ").includes(" " + name + " ");

const pages = fs.readdirSync(ROOT).filter((f) => f.endsWith(".html") && !SKIP.has(f)).sort();
const topics = [];
const items = [];

for (const file of pages) {
  const html = fs.readFileSync(path.join(ROOT, file), "utf8");
  const titleMatch = html.match(/<title>([^<]*)<\/title>/);
  const topic = titleMatch ? text(titleMatch[1]).split(" — ")[0].replace(/ Interview Questions$/, "") : file;
  topics.push({ file, topic });

  // Section headings with their positions, so each question knows its section
  const sections = [...html.matchAll(/<section class="qa-group"[^>]*>\s*<h2>([\s\S]*?)<\/h2>/g)]
    .map((m) => ({ at: m.index, name: text(m[1]) }));

  let n = 0;
  for (const m of html.matchAll(/<details class="qa"([^>]*)>([\s\S]*?)<\/details>/g)) {
    n++;
    const tag = m[1];
    const body = m[2];
    const summary = body.match(/<summary>([\s\S]*?)<\/summary>/);
    const answer = body.slice(summary ? summary.index + summary[0].length : 0)
      .replace(/<div class="explain">[\s\S]*?<\/div>/g, " ");          // keep the excerpt focused on the answer
    const section = sections.filter((s) => s.at < m.index).pop();
    items.push({
      p: file,
      id: "q" + n,
      q: summary ? text(summary[1]) : "",
      l: attr(tag, "data-level") || "",
      t: hasTag(tag, "interview") ? 1 : 0,
      k: hasTag(tag, "coding") ? 1 : 0,
      x: attr(tag, "data-complexity") || "",
      s: attr(tag, "data-source") || "",
      c: section ? section.name : "",
      a: text(answer).slice(0, EXCERPT_CHARS)
    });
  }
}

const data = { generated: new Date().toISOString(), topics, items };
fs.writeFileSync(OUT,
  "/* Generated by tools/build-search-index.js — do not edit by hand. */\n" +
  "window.SEARCH_INDEX = " + JSON.stringify(data) + ";\n");
console.log(`search index: ${items.length} questions from ${pages.length} pages → ${path.relative(ROOT, OUT)} (${(fs.statSync(OUT).size / 1024).toFixed(0)} KB)`);
